import assert from "node:assert/strict";
import { chromium } from "@playwright/test";

const origin = process.argv[2];
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin ?? "") || new URL(origin).port === "43110") {
  throw new Error("private_test_origin_required");
}
let browser;
let page;
let phase = "connect";
try {
  browser = await chromium.connectOverCDP("http://127.0.0.1:9225");
  const context = browser.contexts().find(item => item.pages().some(tab => tab.url().startsWith("http://127.0.0.1:43110/")));
  if (!context) throw new Error("owner_browser_required");
  page = await context.newPage();
  await page.goto(`${origin}/organizations`);
  phase = "real_registry_http";
  const checks = await page.evaluate(async () => {
    const fail = (reason) => ({ status: "failed", reason });
    const accountsResponse = await fetch("/api/v1/accounts?limit=200");
    if (!accountsResponse.ok) return fail("owner_session_required");
    const accounts = await accountsResponse.json();
    if (accounts.page.has_more) return fail("account_selection_incomplete");
    const matches = accounts.items.filter(item => item.provider_key === "ollama" && item.identity_state === "owner_confirmed" && item.organization_id);
    if (matches.length !== 1) return fail("confirmed_account_selection_ambiguous");
    const account = matches[0];
    const path = `/api/v1/organizations/${encodeURIComponent(account.organization_id)}/provider-coverage/ollama`;
    const initial = await fetch(path);
    if (initial.status !== 200) return fail(`initial_http_${initial.status}`);
    const before = await initial.json();
    const existing = before.coverage;
    if (existing !== null && (existing.outcome !== "account" || existing.account_id !== account.account_id || existing.organization_id !== account.organization_id || existing.account_organization_id !== account.organization_id || existing.provider_key !== "ollama" || existing.provenance !== "owner_asserted")) return fail("existing_owner_outcome_differs");
    const baselineVersion = existing?.record_version ?? 0;
    if (!Number.isSafeInteger(baselineVersion) || baselineVersion < 0) return fail("coverage_baseline_invalid");
    const organizationsResponse = await fetch("/api/v1/organizations?limit=200");
    if (!organizationsResponse.ok) return fail("scope_selection_unavailable");
    const organizations = await organizationsResponse.json();
    if (organizations.page.has_more) return fail("scope_selection_incomplete");
    const selection = organizations.items.map(item => item.organization_id).reverse();
    const scopePath = `/api/v1/provider-coverage/ollama?organization_ids=${encodeURIComponent(selection.join(","))}`;
    const scopeBeforeResponse = await fetch(scopePath);
    if (!scopeBeforeResponse.ok) return fail("scope_baseline_unavailable");
    const scopeBefore = await scopeBeforeResponse.json();
    if (scopeBefore.completeness !== "complete" || JSON.stringify(scopeBefore.organization_ids) !== JSON.stringify(selection)) return fail("scope_baseline_incomplete");
    const retainedOtherDeclarations = scopeBefore.items.filter(item => item.organization_id !== account.organization_id);
    const expectedOrganizations = new Set([...scopeBefore.items.map(item => item.organization_id), account.organization_id]);
    const csrf = document.cookie.split(";").map(item => item.trim()).find(item => item.startsWith("agentmonitor_csrf="))?.slice("agentmonitor_csrf=".length);
    if (!csrf) return fail("owner_csrf_required");
    const body = { outcome: "account", account_id: account.account_id, expected_account_record_version: account.record_version, unavailable_reason: null };
    const key = () => crypto.randomUUID();
    const headers = { "Content-Type": "application/json", "X-CSRF-Token": decodeURIComponent(csrf), "Idempotency-Key": key(), "If-Match": initial.headers.get("etag") };
    const put = (data, overrides = {}) => fetch(path, { method: "PUT", headers: { ...headers, ...overrides }, body: JSON.stringify(data) });
    const noProof = await put(body, { "X-CSRF-Token": "" });
    if (noProof.status !== 403) return fail("csrf_not_enforced");
    const forged = await put({ ...body, provenance: "provider_proven" });
    if (forged.status !== 422) return fail("forged_provenance_not_rejected");
    const accountConflict = await put({ ...body, expected_account_record_version: account.record_version + 1 });
    if (accountConflict.status !== 412) return fail("account_version_not_fenced");
    const saved = await put(body);
    if (saved.status !== 200) return fail(`save_http_${saved.status}`);
    const first = await saved.json();
    if (first.provenance !== "owner_asserted" || first.record_version !== baselineVersion + 1 || first.account_id !== account.account_id) return fail("saved_assertion_invalid");
    if (existing && first.coverage_id !== existing.coverage_id) return fail("coverage_identity_changed");
    const replay = await put(body);
    if (replay.status !== 200 || JSON.stringify(await replay.json()) !== JSON.stringify(first)) return fail("idempotent_replay_invalid");
    const stale = await put(body, { "Idempotency-Key": key() });
    if (stale.status !== 412) return fail("stale_create_not_rejected");
    const removed = await fetch(path, { method: "DELETE", headers: { ...headers, "Idempotency-Key": key(), "If-Match": saved.headers.get("etag") } });
    if (removed.status !== 200) return fail(`revoke_http_${removed.status}`);
    const revoked = await removed.json();
    if (revoked.invalidation_reason !== "owner_revoked" || revoked.record_version !== baselineVersion + 2) return fail("revocation_not_retained");
    const fresh = await fetch(path);
    const retained = await fresh.json();
    if (retained.coverage?.invalidation_reason !== "owner_revoked" || retained.coverage.record_version !== baselineVersion + 2) return fail("revoked_read_invalid");
    const scoped = await fetch(scopePath);
    if (scoped.status !== 200) return fail("scope_read_failed");
    const snapshot = await scoped.json();
    if (JSON.stringify(snapshot.organization_ids) !== JSON.stringify(selection) || JSON.stringify(snapshot.items.map(item => item.organization_id)) !== JSON.stringify(selection.filter(id => expectedOrganizations.has(id))) || snapshot.completeness !== "complete") return fail("sparse_selection_not_preserved");
    if (JSON.stringify(snapshot.items.filter(item => item.organization_id !== account.organization_id)) !== JSON.stringify(retainedOtherDeclarations)) return fail("other_declarations_changed");
    const duplicate = await fetch(`/api/v1/provider-coverage/ollama?organization_ids=${encodeURIComponent([account.organization_id, account.organization_id].join(","))}`);
    if (duplicate.status !== 422) return fail("duplicate_scope_not_rejected");
    const after = await fetch(`/api/v1/accounts/${encodeURIComponent(account.account_id)}`);
    if (!after.ok || (await after.json()).record_version !== account.record_version) return fail("coverage_changed_account");
    return { status: "passed", reason: null, organizationId: account.organization_id, accountId: account.account_id, baselineVersion, coverageId: first.coverage_id };
  });
  assert.equal(checks.status, "passed", checks.reason ?? "http_failed");
  phase = "built_editor";
  await page.reload();
  await page.getByRole("heading", { name: "Organization registry", exact: true }).waitFor();
  const card = page.locator(".record-card").filter({ has: page.locator(`[id="rename-organization-${checks.organizationId}"]`) });
  const editor = card.getByText("Provider coverage", { exact: true });
  await editor.click();
  await page.getByLabel("Coverage arrangement").first().waitFor();
  assert.equal(await page.getByLabel("Provider", { exact: true }).first().inputValue(), "ollama");
  await page.getByLabel("Coverage arrangement").first().selectOption("account");
  await page.getByLabel("Account", { exact: true }).first().selectOption(checks.accountId);
  await page.getByRole("button", { name: "Save coverage", exact: true }).first().click();
  await page.getByText("Coverage saved as an owner declaration.", { exact: true }).waitFor();
  const readCoverage = () => page.evaluate(async organizationId => {
    const response = await fetch(`/api/v1/organizations/${encodeURIComponent(organizationId)}/provider-coverage/ollama`);
    if (!response.ok) return null;
    return (await response.json()).coverage;
  }, checks.organizationId);
  const reasserted = await readCoverage();
  assert.equal(reasserted?.record_version, checks.baselineVersion + 3, "editor_reassert_version_invalid");
  assert.equal(reasserted?.coverage_id === checks.coverageId, true, "editor_reassert_identity_changed");
  assert.equal(reasserted?.invalidated_at, null, "editor_reassert_not_current");
  await page.getByRole("button", { name: "Remove declaration", exact: true }).first().click();
  await page.getByText("Coverage declaration removed. The account connection is unchanged.", { exact: true }).waitFor();
  const editorRevoked = await readCoverage();
  assert.equal(editorRevoked?.record_version, checks.baselineVersion + 4, "editor_revoke_version_invalid");
  assert.equal(editorRevoked?.invalidation_reason, "owner_revoked", "editor_revoke_not_retained");
  await page.getByLabel("Coverage arrangement").first().selectOption("unavailable");
  assert.equal(await page.getByLabel("Why unavailable").first().inputValue(), "");
  assert.equal(await page.getByRole("button", { name: "Save coverage", exact: true }).first().isDisabled(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  console.log(JSON.stringify({status:"passed",http:true,editor:true,shared_unavailable_write:"not_run"}));
} catch (error) {
  const reason = error instanceof assert.AssertionError ? error.message.split("\n")[0] : "";
  const known = /^[a-z_0-9]+$/.test(reason) ? reason : "verification_failed";
  console.log(JSON.stringify({status:"failed",phase,reason:known}));
  process.exitCode = 1;
} finally {
  if (page) await page.close();
  if (browser) await browser.close();
}
